#!/usr/bin/env bun
/**
 * Writes the App Router patterns a log line may name (ISSUE-832) to
 * packages/logger/src/app-routes.generated.ts: `bun log:routes`. A page or
 * route handler added to `apps/web` or `apps/admin` is one run of this, never a
 * hand edit; `scripts/log-routes.test.ts` fails while the file is stale.
 */
import { readdirSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dir, '..');
const apps = ['apps/web/src/app', 'apps/admin/src/app'];
export const GENERATED = 'packages/logger/src/app-routes.generated.ts';

/**
 * Each page or route handler under an App Router directory, as the pattern
 * Next reports in `onRequestError`'s `routePath`: route groups and parallel
 * slots dropped, dynamic segments kept in brackets.
 */
export const appRoutePatterns = (app: string): string[] =>
  (readdirSync(path.join(root, app), { recursive: true }) as string[])
    .filter((file) => /(^|\/)(page\.tsx|route\.ts)$/.test(file))
    .map(
      (file) =>
        `/${file}`
          .replace(/\/(page\.tsx|route\.ts)$/, '')
          .split('/')
          .filter(
            (segment) => !/^\(.*\)$/.test(segment) && !segment.startsWith('@'),
          )
          .join('/') || '/',
    );

/** The generated module's text for every pattern of both apps, sorted. */
export const renderAppRoutes = (
  patterns: readonly string[] = apps.flatMap(appRoutePatterns),
): string =>
  [
    '// Generated by `bun log:routes` from the pages and route handlers of',
    '// apps/web and apps/admin. Do not edit: add the route, then run it.',
    'export const appRoutes: readonly string[] = [',
    ...[...new Set(patterns)].sort().map((pattern) => `  '${pattern}',`),
    '];',
    '',
  ].join('\n');

if (import.meta.main) {
  await Bun.write(path.join(root, GENERATED), renderAppRoutes());
  process.stdout.write(`wrote ${GENERATED}\n`);
}
