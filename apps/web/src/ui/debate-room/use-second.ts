'use client';
import { useEffect, useState } from 'react';

export type MonotonicClock = () => number;

/** Default monotonic source: the browser's high-resolution clock. */
export const defaultMonotonicClock: MonotonicClock = () => performance.now();

/** The latency envelope a sample must fit to be trusted. */
export const MAX_SAMPLE_RTT_MS = 2000;

/** How often a mounted Round re-reads, resampling even an unchanged version. */
export const RESAMPLE_EVERY_MS = 30_000;

/** One measured authorization read: millisecond server time inside a bounded interval. */
export type RoundTimeSample = {
  /** Milliseconds generated by the server's own clock during this request interval. */
  readonly serverNowMs: number;
  readonly sentAtMs: number;
  readonly receivedAtMs: number;
  /** Mandatory, strictly increasing per-request ordering key. */
  readonly generation: number;
};

/** The one time seam a mounted Round shares between display and media deadlines. */
export type RoundTime = {
  nowMs(): number;
  sample(candidate: RoundTimeSample): boolean;
  currentSample(): RoundTimeSample;
  currentUncertaintyMs(): number;
};

/**
 * One round-scoped calibrated clock. A fresh authorized sample is re-anchored
 * atomically: server time is estimated at receive as `serverNowMs + RTT/2`
 * with uncertainty `RTT/2`, so older generations, high-latency envelopes and
 * clock rollbacks can never replace the accepted sample. Advances only on
 * injected monotonic elapsed time; browser wall-clock skew, adjustment,
 * suspension and rejoin cannot move it — suspension is corrected by a fresh
 * sample, not by a frozen anchor.
 */
export function createRoundTime(options: {
  readonly monotonicNowMs?: MonotonicClock;
}): RoundTime {
  const monotonic = options.monotonicNowMs ?? defaultMonotonicClock;
  let estimated = 0;
  let monoAtAnchor = 0;
  let uncertainty = Number.POSITIVE_INFINITY;
  let latestGeneration = -1;
  let filled = false;

  function sample(candidate: RoundTimeSample): boolean {
    const rtt = candidate.receivedAtMs - candidate.sentAtMs;
    if (!Number.isFinite(rtt) || rtt < 0 || rtt > MAX_SAMPLE_RTT_MS)
      return false;
    if (candidate.generation <= latestGeneration) return false;
    // Server time measured inside this interval; midpoint projects it to receive.
    const serverAtReceive = candidate.serverNowMs + rtt / 2;
    // Rollback prevention against the currently accepted anchor.
    if (filled && serverAtReceive < estimated - MAX_SAMPLE_RTT_MS) return false;
    estimated = serverAtReceive;
    monoAtAnchor = candidate.receivedAtMs;
    uncertainty = rtt / 2;
    latestGeneration = candidate.generation;
    filled = true;
    return true;
  }

  function nowMs(): number {
    if (!filled) return 0;
    return estimated + (monotonic() - monoAtAnchor);
  }

  return {
    nowMs,
    sample,
    currentSample: () => {
      if (!filled)
        throw new Error('No authorized server sample has been accepted yet');
      return {
        serverNowMs: estimated,
        sentAtMs: monoAtAnchor,
        receivedAtMs: monoAtAnchor,
        generation: latestGeneration,
      };
    },
    currentUncertaintyMs: () => uncertainty,
  };
}

/** Pure projection of one sample to a later monotonic instant. */
export function calibratedNowMs(sample: RoundTimeSample, monotonicNowMs: number): number {
  return sample.serverNowMs + (monotonicNowMs - sample.receivedAtMs);
}

/**
 * The server's clock at one instant, read once a second: the clock edge of a
 * live view. It starts from the server's render instant as the hydration seed
 * only, then advances from one shared round clock every component receives.
 * Re-ticks on visibility change; a fresh authorized sample re-anchors it.
 */
export function useSecond(
  renderedAtMs: number,
  roundTime?: RoundTime,
): number {
  const [clock] = useState(() => {
    if (roundTime) return roundTime;
    const seed = createRoundTime({ monotonicNowMs: defaultMonotonicClock });
    const at = defaultMonotonicClock();
    seed.sample({
      serverNowMs: renderedAtMs,
      sentAtMs: at,
      receivedAtMs: at,
      generation: 0,
    });
    return seed;
  });
  const [now, setNow] = useState(() => clock.nowMs());
  useEffect(() => {
    const tick = () => setNow(clock.nowMs());
    tick();
    const timer = window.setInterval(tick, 1000);
    const onVisibility = () => {
      if (document.visibilityState === 'visible') tick();
    };
    document.addEventListener('visibilitychange', onVisibility);
    return () => {
      window.clearInterval(timer);
      document.removeEventListener('visibilitychange', onVisibility);
    };
  }, [clock]);
  return now;
}
